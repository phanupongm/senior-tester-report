def e(x):
    return html.escape(str(x)) if x is not None else ""


def confirmed(f):
    return f.get("confidence", "confirmed") != "suspected"


# --------------------------------------------------------------------------- validation

def validate(data):
    errs = []
    if not isinstance(data, dict):
        return ["top level must be a JSON object"]
    for key in ("meta", "summary", "scores", "findings"):
        if key not in data:
            errs.append(f"missing top-level key: {key}")
    scores = data.get("scores", {}) or {}
    for a in AREAS:
        s = scores.get(a)
        if not isinstance(s, dict):
            errs.append(f"scores.{a} missing")
        elif not isinstance(s.get("score"), (int, float)) or isinstance(s.get("score"), bool) or not 0 <= s["score"] <= 10:
            errs.append(f"scores.{a}.score must be a number 0-10")
    for k in scores:
        if k not in AREAS:
            errs.append(f"scores.{k}: unknown area (use one of {list(AREAS)})")
    ids = set()
    for i, f in enumerate(data.get("findings", []) or []):
        tag = f.get("id", f"#{i}")
        for k in ("id", "title", "area", "severity"):
            if not f.get(k):
                errs.append(f"finding {tag}: missing {k}")
        if f.get("id") in ids:
            errs.append(f"duplicate finding id {f['id']}")
        ids.add(f.get("id"))
        if f.get("severity") and f["severity"] not in SEVERITIES:
            errs.append(f"finding {tag}: severity must be one of {SEVERITIES}")
        if f.get("area") and f["area"] not in AREAS:
            errs.append(f"finding {tag}: area must be one of {list(AREAS)}")
        if f.get("confidence") not in (None, "confirmed", "suspected"):
            errs.append(f"finding {tag}: confidence must be confirmed or suspected")
        if f.get("steps") is not None and not isinstance(f["steps"], list):
            errs.append(f"finding {tag}: steps must be a list of strings")
        if f.get("locations") is not None and not isinstance(f["locations"], list):
            errs.append(f"finding {tag}: locations must be a list of 'path:line' strings")
        if f.get("severity") in ("Critical", "High") and confirmed(f):
            if not f.get("steps"):
                errs.append(f"finding {tag}: confirmed Critical/High needs steps")
            if not (f.get("location") or f.get("url")):
                errs.append(f"finding {tag}: confirmed Critical/High needs location or url")
        if f.get("id") and f.get("area") in ID_PREFIX and not str(f["id"]).startswith(ID_PREFIX[f["area"]] + "-"):
            errs.append(f"finding {tag}: id should start with '{ID_PREFIX[f['area']]}-' for area {f['area']}")
    for j in data.get("journeys", []) or []:
        if j.get("result") not in JOURNEY_RESULTS:
            errs.append(f"journey '{j.get('goal')}': result must be one of {sorted(JOURNEY_RESULTS)}")
    for c in data.get("checks", []) or []:
        if c.get("status") not in CHECK_STATUS:
            errs.append(f"check '{c.get('item')}': status must be one of {sorted(CHECK_STATUS)}")
    return errs


# --------------------------------------------------------------------------- scoring

def overall(data):
    total = sum(data["scores"][a]["score"] * w for a, w in AREAS.items())
    score = round(total / sum(AREAS.values()) * 10)
    grade = "A" if score >= 90 else "B" if score >= 80 else "C" if score >= 70 else "D" if score >= 60 else "F"
    order = "ABCDF"
    cap = None
    fs = [f for f in data["findings"] if confirmed(f)]
    if any(f["severity"] == "Critical" for f in fs):
        if order.index(grade) < order.index("D"):
            grade, cap = "D", "cap_crit"
    elif any(f["severity"] == "High" and f["area"] == "security" for f in fs):
        if order.index(grade) < order.index("C"):
            grade, cap = "C", "cap_sec"
    return score, grade, cap


def verdict(data):
    fs = [f for f in data["findings"] if confirmed(f)]
    if any(f["severity"] in ("Critical", "High") for f in fs):
        return "block"
    if any(f["severity"] == "Medium" for f in data["findings"]):
        return "risky"
    return "ok"


def sort_findings(fs):
    return sorted(fs, key=lambda f: (SEV_RANK[f["severity"]], 0 if confirmed(f) else 1, f["id"]))


def grade_color(score):
    return "var(--ok)" if score >= 80 else "var(--med)" if score >= 60 else "var(--bad)"


def bar_color(v):
    return "var(--ok)" if v >= 8 else "var(--med)" if v >= 5 else "var(--bad)"


# --------------------------------------------------------------------------- html

def embed(f, shots_dir):
    if not shots_dir:
        return ""
    candidates = [f.get("screenshot")] if f.get("screenshot") else []
    candidates += [f"{f['id']}.png", f"{f['id']}.jpg", f"{f['id'].lower()}.png"]
    for name in candidates:
        p = Path(shots_dir) / name
        if p.is_file():
            mime = mimetypes.guess_type(p.name)[0] or "image/png"
            b64 = base64.b64encode(p.read_bytes()).decode()
            return f'<img class="shot" loading="lazy" alt="{e(f["id"])} screenshot" src="data:{mime};base64,{b64}">'
    if f.get("screenshot"):
        print(f"warning: screenshot not found for {f['id']}: {f['screenshot']}", file=sys.stderr)
    return ""


