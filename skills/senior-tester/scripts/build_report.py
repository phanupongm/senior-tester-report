def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("findings")
    ap.add_argument("output", help="HTML report path")
    ap.add_argument("--shots", help="folder with screenshots (matched by 'screenshot' field or <finding-id>.png)")
    ap.add_argument("--previous", help="previous findings.json to compare against")
    ap.add_argument("--md", help="also write a Markdown summary (for PRs / issues)")
    ap.add_argument("--sarif", help="also write SARIF 2.1.0 (for GitHub code scanning)")
    ap.add_argument("--lang", help="override report UI language (en, th)")
    a = ap.parse_args()

    try:
        data = json.loads(Path(a.findings).read_text(encoding="utf-8"))
    except json.JSONDecodeError as ex:
        sys.exit(f"{a.findings} is not valid JSON: {ex}")
    errs = validate(data)
    if errs:
        print(f"{a.findings} has {len(errs)} problem(s):", file=sys.stderr)
        for x in errs:
            print("  -", x, file=sys.stderr)
        sys.exit(1)
    prev = None
    if a.previous:
        prev = json.loads(Path(a.previous).read_text(encoding="utf-8"))
        perr = validate(prev)
        if perr:
            print(f"warning: previous file has problems, comparison may be partial: {perr[0]}", file=sys.stderr)
            if any("scores." in x for x in perr):
                prev = None
    lang = a.lang or data["meta"].get("language", "en")
    if lang not in L:
        lang = "en"

    Path(a.output).write_text(render_html(data, a.shots, prev, lang), encoding="utf-8")
    written = [a.output]
    if a.md:
        Path(a.md).write_text(render_md(data, prev, lang), encoding="utf-8")
        written.append(a.md)
    if a.sarif:
        Path(a.sarif).write_text(json.dumps(render_sarif(data), indent=2, ensure_ascii=False), encoding="utf-8")
        written.append(a.sarif)
    score, grade, cap = overall(data)
    crit = sum(1 for f in data["findings"] if f["severity"] == "Critical")
    high = sum(1 for f in data["findings"] if f["severity"] == "High")
    print(f"grade {grade} ({score}/100){' [capped]' if cap else ''} · {len(data['findings'])} findings "
          f"({crit} Critical, {high} High) · verdict: {verdict(data)}")
    print("wrote " + ", ".join(written))


if __name__ == "__main__":
    main()
