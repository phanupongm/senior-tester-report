def md_escape(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def render_md(data, prev, lang):
    t = L.get(lang, L["en"])
    m = data["meta"]
    score, grade, cap = overall(data)
    v = verdict(data)
    fs = sort_findings(data["findings"])
    o = [f"# {m.get('system', 'System')} — QA {grade} ({score}/100)", ""]
    o.append(f"**{t['verdict_' + v]}** — {t['verdict_' + v + '_d']}" + (f"  \n_{t[cap]}_" if cap else ""))
    o += ["", data["summary"], ""]
    counts = {s: sum(1 for f in fs if f["severity"] == s) for s in SEVERITIES}
    o.append(" · ".join(f"**{s}** {c}" for s, c in counts.items() if c) or t["no_findings"])
    o += ["", f"## {t['scores']}", "", f"| | {t['overall']} | |", "|---|---|---|"]
    ps = (prev or {}).get("scores", {})
    for a in AREAS:
        s = data["scores"][a]
        d = ""
        if a in ps:
            diff = s["score"] - ps[a]["score"]
            d = f" ({'+' if diff > 0 else ''}{diff:g})" if diff else ""
        o.append(f"| {t['areas'][a]} | {s['score']:g}/10{d} | {md_escape(s.get('why', ''))} |")
    if prev:
        old = {f["id"] for f in prev.get("findings", [])}
        cur = {f["id"] for f in fs}
        o += ["", f"## {t['compare']}", "",
              f"- {t['fixed']}: {', '.join(sorted(old - cur)) or t['none']}",
              f"- {t['new']}: {', '.join(sorted(cur - old)) or t['none']}",
              f"- {t['still']}: {', '.join(sorted(cur & old)) or t['none']}"]
    o += ["", f"## {t['findings']}", ""]
    for f in fs:
        sus = f" _({t['suspected']})_" if not confirmed(f) else ""
        o.append(f"### {f['id']} · {f['severity']} · {f['title']}{sus}")
        o.append("")
        if f.get("location"):
            o.append(f"- **{t['where']}:** `{f['location']}`")
        for x in (f.get("locations") or []):
            if x != f.get("location"):
                o.append(f"- **{t['also']}:** `{x}`")
        if f.get("url"):
            o.append(f"- **{t['url']}:** `{f['url']}`")
        if f.get("owasp") or f.get("cwe"):
            o.append(f"- **OWASP / CWE:** {' · '.join(x for x in [f.get('owasp'), f.get('cwe')] if x)}")
        if f.get("steps"):
            o.append(f"- **{t['steps']}:**")
            o += [f"  {i}. {s}" for i, s in enumerate(f["steps"], 1)]
        if f.get("expected"):
            o.append(f"- **{t['expected']}:** {f['expected']}")
        if f.get("actual"):
            o.append(f"- **{t['actual']}:** {f['actual']}")
        if f.get("fix"):
            o.append(f"- **{t['fix']}:** {f['fix']}")
        if f.get("fix_code"):
            o += ["", "```", f["fix_code"], "```"]
        o.append("")
    ideas = data.get("ideas") or []
    if ideas:
        o += [f"## {t['ideas']}", "", f"| | {t['effort']} | {t['impact']} | |", "|---|---|---|---|"]
        o += [f"| {md_escape(i.get('title'))} | {i.get('effort', '?')} | {i.get('impact', '?')} | {md_escape(i.get('why', ''))} |" for i in ideas]
        o.append("")
    o.append(f"<sub>{t['footer'].format(v=VERSION)}</sub>")
    return "\n".join(o) + "\n"


# --------------------------------------------------------------------------- sarif

SARIF_LEVEL = {"Critical": "error", "High": "error", "Medium": "warning", "Low": "note", "Info": "note"}
SARIF_SCORE = {"Critical": "9.5", "High": "8.0", "Medium": "5.5", "Low": "3.0", "Info": "1.0"}


def parse_loc(s):
    if not s:
        return None
    m = re.match(r"^(.*?):(\d+)(?::(\d+))?$", s.strip())
    if m:
        path, line = m.group(1), int(m.group(2))
    else:
        path, line = s.strip(), 1
    if re.match(r"^[a-z]+://", path) or path.startswith("/api") or " " in path:
        return None
    return path.lstrip("./"), max(line, 1)


def render_sarif(data):
    rules, results, seen = [], [], set()
    for f in sort_findings(data["findings"]):
        locs = [parse_loc(x) for x in ([f.get("location")] + list(f.get("locations") or [])) if x]
        locs = [x for i, x in enumerate(locs) if x and x not in locs[:i]]
        if not locs:
            continue  # SARIF/code scanning needs a file location
        if f["id"] not in seen:
            seen.add(f["id"])
            tags = [f["area"]] + [x for x in (f.get("owasp"), f.get("cwe")) if x]
            if f["area"] == "security":
                tags.append("security")
            rule = {
                "id": f["id"],
                "name": re.sub(r"[^A-Za-z0-9]+", "", f["title"].title())[:60] or f["id"],
                "shortDescription": {"text": f["title"][:200]},
                "fullDescription": {"text": (f.get("actual") or f["title"])[:1000]},
                "help": {"text": f.get("fix") or "See the senior-tester report.",
                         "markdown": (f.get("fix") or "See the senior-tester report.")
                         + (f"\n\n```\n{f['fix_code']}\n```" if f.get("fix_code") else "")},
                "defaultConfiguration": {"level": SARIF_LEVEL[f["severity"]]},
                "properties": {"tags": tags, "precision": "high" if confirmed(f) else "medium"},
            }
            if f["area"] == "security":
                rule["properties"]["security-severity"] = SARIF_SCORE[f["severity"]]
            rules.append(rule)
        msg = f["title"]
        if f.get("steps"):
            msg += " — Steps: " + " → ".join(f["steps"])
        results.append({
            "ruleId": f["id"],
            "level": SARIF_LEVEL[f["severity"]],
            "message": {"text": msg[:2000]},
            "locations": [{"physicalLocation": {"artifactLocation": {"uri": p, "uriBaseId": "%SRCROOT%"},
                                                "region": {"startLine": ln}}} for p, ln in locs],
            "partialFingerprints": {"seniorTesterId/v1": f["id"]},
        })
    return {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {"driver": {"name": "senior-tester", "version": VERSION,
                                "informationUri": "https://github.com/phanupongm/senior-tester-report",
                                "rules": rules}},
            "results": results,
        }],
    }


